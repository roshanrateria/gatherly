import React, { useState } from 'react';
import {
  CalendarDays,
  Clock,
  Plus,
  Download,
  AlertTriangle,
  CheckCircle2,
  Calendar,
  Layers,
  Edit2,
  Trash2,
  RefreshCw,
  ArrowRight,
  ShieldAlert,
} from 'lucide-react';
import { AppState, Milestone, TaskPriority } from '../../types/index';
import {
  calculateDaysBetween,
  recalculateTimelineForNewDate,
  checkMilestoneDependencies,
} from '../../lib/deterministicTimeline';
import { generateMilestonesIcs, downloadIcsFile } from '../../lib/icsExport';

interface TimelineTabProps {
  state: AppState;
  onUpdateState: (newState: AppState) => void;
  onShowToast: (type: 'success' | 'warning' | 'error' | 'info', title: string, msg?: string) => void;
}

export const TimelineTab: React.FC<TimelineTabProps> = ({ state, onUpdateState, onShowToast }) => {
  const { event, milestones, tasks } = state;
  const [viewMode, setViewMode] = useState<'timeline' | 'calendar'>('timeline');
  const [rescheduleModalOpen, setRescheduleModalOpen] = useState(false);
  const [newTargetDate, setNewTargetDate] = useState(event.startDate);

  // Milestone Add/Edit
  const [milestoneModalOpen, setMilestoneModalOpen] = useState(false);
  const [editingMilestone, setEditingMilestone] = useState<Milestone | null>(null);
  const [mTitle, setMTitle] = useState('');
  const [mCategory, setMCategory] = useState('Production');
  const [mDueDate, setMDueDate] = useState(event.startDate);
  const [mPriority, setMPriority] = useState<TaskPriority>('high');
  const [mNotes, setMNotes] = useState('');

  const dependencyIssues = checkMilestoneDependencies(milestones);
  const issuesWithWarnings = dependencyIssues.filter((i) => i.hasDependencyIssue);

  const toggleMilestoneComplete = (milestoneId: string) => {
    const updated = milestones.map((m) =>
      m.id === milestoneId ? { ...m, completed: !m.completed } : m
    );
    onUpdateState({ ...state, milestones: updated });
  };

  const handleExportIcs = () => {
    const icsContent = generateMilestonesIcs(milestones, event.title);
    downloadIcsFile(icsContent, `${event.title.replace(/\s+/g, '_')}_milestones.ics`);
    onShowToast('success', 'ICS Calendar Exported', 'Import into Google Calendar or Apple iCal.');
  };

  const handleRescheduleAll = (e: React.FormEvent) => {
    e.preventDefault();
    if (!newTargetDate) return;

    const { updatedMilestones, updatedTasks } = recalculateTimelineForNewDate(
      milestones,
      tasks,
      newTargetDate
    );

    // Also update event startDate & endDate
    const d = new Date(newTargetDate);
    d.setDate(d.getDate() + (event.durationDays - 1));
    const newEndDate = d.toISOString().split('T')[0];

    onUpdateState({
      ...state,
      event: { ...event, startDate: newTargetDate, endDate: newEndDate },
      milestones: updatedMilestones,
      tasks: updatedTasks,
    });

    setRescheduleModalOpen(false);
    onShowToast(
      'success',
      'Event Rescheduled & Deadlines Recalibrated',
      `Shifted to ${newTargetDate}. All dependent milestone offsets recalculated.`
    );
  };

  const handleSaveMilestone = (e: React.FormEvent) => {
    e.preventDefault();
    if (!mTitle.trim()) return;

    const daysBefore = calculateDaysBetween(mDueDate, event.startDate);

    if (editingMilestone) {
      const updated = milestones.map((m) =>
        m.id === editingMilestone.id
          ? {
              ...m,
              title: mTitle,
              category: mCategory,
              dueDate: mDueDate,
              daysBeforeEvent: daysBefore,
              priority: mPriority,
              notes: mNotes,
            }
          : m
      );
      onUpdateState({ ...state, milestones: updated });
      onShowToast('success', 'Milestone Updated', mTitle);
    } else {
      const newM: Milestone = {
        id: `m_${Date.now()}`,
        title: mTitle,
        category: mCategory,
        dueDate: mDueDate,
        daysBeforeEvent: daysBefore,
        completed: false,
        priority: mPriority,
        dependencies: [],
        isAtRisk: mDueDate < new Date().toISOString().split('T')[0],
        notes: mNotes,
        autoGenerated: false,
      };
      onUpdateState({ ...state, milestones: [...milestones, newM] });
      onShowToast('success', 'Milestone Created', mTitle);
    }

    setMilestoneModalOpen(false);
    setEditingMilestone(null);
  };

  const handleDeleteMilestone = (mId: string) => {
    onUpdateState({ ...state, milestones: milestones.filter((m) => m.id !== mId) });
    onShowToast('info', 'Milestone Removed');
  };

  return (
    <div className="space-y-6 pb-12 animate-in fade-in duration-300">
      {/* Top Banner */}
      <div className="flex flex-wrap items-center justify-between gap-4">
        <div>
          <h2 className="text-xl font-bold font-editorial text-slate-900">
            Dynamic Milestones &amp; Planning Timeline
          </h2>
          <p className="text-xs text-slate-500">
            Calculated from event date ({event.startDate}), {event.durationDays}-day duration, and
            lead time complexity
          </p>
        </div>

        <div className="flex items-center gap-2">
          {/* Switch View */}
          <div className="flex bg-slate-100 p-0.5 rounded-lg border border-slate-200 text-xs">
            <button
              onClick={() => setViewMode('timeline')}
              className={`px-3 py-1.5 rounded-md font-medium transition-colors ${
                viewMode === 'timeline' ? 'bg-white shadow-2xs text-slate-900' : 'text-slate-500'
              }`}
            >
              Timeline View
            </button>
            <button
              onClick={() => setViewMode('calendar')}
              className={`px-3 py-1.5 rounded-md font-medium transition-colors ${
                viewMode === 'calendar' ? 'bg-white shadow-2xs text-slate-900' : 'text-slate-500'
              }`}
            >
              Calendar View
            </button>
          </div>

          <button
            onClick={() => setRescheduleModalOpen(true)}
            className="flex items-center gap-1.5 px-3 py-1.5 text-xs font-semibold rounded-lg bg-white border border-slate-300 text-slate-700 hover:bg-slate-50 transition-colors"
          >
            <RefreshCw className="w-3.5 h-3.5 text-purple-900" />
            <span>Reschedule Event</span>
          </button>

          <button
            onClick={handleExportIcs}
            className="flex items-center gap-1.5 px-3 py-1.5 text-xs font-semibold rounded-lg bg-white border border-slate-300 text-slate-700 hover:bg-slate-50 transition-colors"
          >
            <Download className="w-3.5 h-3.5 text-indigo-700" />
            <span>Export .ICS</span>
          </button>

          <button
            onClick={() => {
              setEditingMilestone(null);
              setMTitle('');
              setMCategory('Production');
              setMDueDate(event.startDate);
              setMPriority('high');
              setMNotes('');
              setMilestoneModalOpen(true);
            }}
            className="flex items-center gap-1.5 px-3.5 py-1.5 text-xs font-bold rounded-lg bg-purple-900 hover:bg-purple-950 text-white shadow-xs transition-colors"
          >
            <Plus className="w-3.5 h-3.5 text-amber-300" />
            <span>Add Milestone</span>
          </button>
        </div>
      </div>

      {/* Dependency Warning Banner */}
      {issuesWithWarnings.length > 0 && (
        <div className="p-3.5 bg-amber-50 border border-amber-200 rounded-xl text-xs text-amber-900 space-y-1">
          <div className="flex items-center gap-2 font-bold">
            <AlertTriangle className="w-4 h-4 text-amber-600" />
            <span>Milestone Dependency Warning Detected</span>
          </div>
          {issuesWithWarnings.map((iw) => (
            <p key={iw.milestoneId} className="text-slate-700 pl-6">
              • {iw.issueDescription}
            </p>
          ))}
        </div>
      )}

      {/* Content Rendering: Timeline vs Calendar */}
      {viewMode === 'timeline' ? (
        <div className="relative border-l-2 border-purple-200 ml-4 pl-6 space-y-6 pt-2">
          {milestones.map((m, idx) => {
            const isOverdue = m.isAtRisk && !m.completed;
            return (
              <div
                key={m.id}
                className="relative group transition-all animate-in fade-in slide-in-from-left-2"
              >
                {/* Node marker */}
                <button
                  onClick={() => toggleMilestoneComplete(m.id)}
                  className={`absolute -left-[35px] top-3.5 w-6 h-6 rounded-full border-2 flex items-center justify-center transition-all cursor-pointer ${
                    m.completed
                      ? 'bg-emerald-600 border-emerald-600 text-white'
                      : isOverdue
                      ? 'bg-rose-500 border-rose-500 text-white animate-pulse'
                      : 'bg-white border-purple-800 text-transparent hover:text-purple-800'
                  }`}
                  title={m.completed ? 'Mark Incomplete' : 'Mark Completed'}
                >
                  <CheckCircle2 className="w-4 h-4" />
                </button>

                {/* Milestone Card */}
                <div
                  className={`p-4 rounded-xl border transition-all ${
                    m.completed
                      ? 'bg-slate-50/80 border-slate-200 opacity-70'
                      : isOverdue
                      ? 'bg-rose-50/40 border-rose-200'
                      : 'bg-white border-slate-200 shadow-2xs hover:shadow-xs'
                  }`}
                >
                  <div className="flex flex-wrap items-start justify-between gap-2">
                    <div>
                      <div className="flex items-center gap-2">
                        <span
                          className={`text-xs font-bold ${
                            m.completed ? 'line-through text-slate-500' : 'text-slate-900'
                          }`}
                        >
                          {m.title}
                        </span>
                        <span className="text-[10px] font-semibold px-2 py-0.2 rounded bg-purple-50 text-purple-900 border border-purple-100">
                          {m.category}
                        </span>
                        <span
                          className={`text-[9px] font-bold uppercase px-1.5 py-0.2 rounded ${
                            m.priority === 'high'
                              ? 'bg-rose-100 text-rose-800'
                              : m.priority === 'medium'
                              ? 'bg-amber-100 text-amber-800'
                              : 'bg-slate-100 text-slate-700'
                          }`}
                        >
                          {m.priority}
                        </span>
                      </div>

                      <p className="text-xs text-slate-600 mt-1 leading-relaxed">
                        {m.notes || 'Core event milestone deliverables'}
                      </p>
                    </div>

                    <div className="flex items-center gap-3">
                      <div className="text-right">
                        <span className="text-xs font-bold text-slate-800 block">{m.dueDate}</span>
                        <span
                          className={`text-[10px] font-semibold ${
                            isOverdue
                              ? 'text-rose-600'
                              : m.completed
                              ? 'text-emerald-700'
                              : 'text-slate-500'
                          }`}
                        >
                          {m.completed
                            ? 'Completed'
                            : isOverdue
                            ? 'Overdue / At Risk'
                            : `${m.daysBeforeEvent} days before event`}
                        </span>
                      </div>

                      <div className="flex items-center gap-1">
                        <button
                          onClick={() => {
                            setEditingMilestone(m);
                            setMTitle(m.title);
                            setMCategory(m.category);
                            setMDueDate(m.dueDate);
                            setMPriority(m.priority);
                            setMNotes(m.notes || '');
                            setMilestoneModalOpen(true);
                          }}
                          className="p-1.5 text-slate-400 hover:text-slate-700 rounded"
                        >
                          <Edit2 className="w-3.5 h-3.5" />
                        </button>
                        <button
                          onClick={() => handleDeleteMilestone(m.id)}
                          className="p-1.5 text-slate-400 hover:text-rose-600 rounded"
                        >
                          <Trash2 className="w-3.5 h-3.5" />
                        </button>
                      </div>
                    </div>
                  </div>
                </div>
              </div>
            );
          })}
        </div>
      ) : (
        /* Calendar View */
        <div className="bg-white rounded-2xl border border-slate-200 p-6 shadow-2xs">
          <div className="flex items-center justify-between mb-4">
            <h3 className="text-sm font-bold text-slate-800 font-editorial">
              Milestone Schedule Distribution
            </h3>
            <span className="text-xs text-slate-500">
              Event Window: {event.startDate} to {event.endDate}
            </span>
          </div>

          <div className="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-3 gap-3">
            {milestones.map((m) => (
              <div
                key={m.id}
                className="p-3 rounded-xl border border-slate-200 bg-[#FAF9F7] space-y-1.5"
              >
                <div className="flex items-center justify-between">
                  <span className="text-xs font-bold text-slate-900">{m.dueDate}</span>
                  <span
                    className={`text-[9px] font-bold uppercase px-1.5 py-0.2 rounded ${
                      m.completed
                        ? 'bg-emerald-100 text-emerald-800'
                        : m.isAtRisk
                        ? 'bg-rose-100 text-rose-800'
                        : 'bg-slate-200 text-slate-700'
                    }`}
                  >
                    {m.completed ? 'Done' : m.isAtRisk ? 'At Risk' : 'Upcoming'}
                  </span>
                </div>
                <h4 className="text-xs font-semibold text-slate-800">{m.title}</h4>
                <p className="text-[11px] text-slate-500 line-clamp-1">{m.category}</p>
              </div>
            ))}
          </div>
        </div>
      )}

      {/* Reschedule Modal */}
      {rescheduleModalOpen && (
        <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-slate-900/60 backdrop-blur-xs">
          <form
            onSubmit={handleRescheduleAll}
            className="bg-white rounded-2xl shadow-2xl border border-slate-200 max-w-md w-full p-6 space-y-4 animate-in fade-in zoom-in-95"
          >
            <h3 className="text-base font-bold text-slate-900 font-editorial">
              Reschedule Event &amp; Recalculate Milestones
            </h3>
            <p className="text-xs text-slate-600 leading-relaxed">
              Updating your event date recalculates all affected deadlines, tasks, and at-risk flags
              using your event&apos;s lead-time models.
            </p>

            <div>
              <label className="block text-xs font-medium text-slate-700 mb-1">
                New Event Start Date
              </label>
              <input
                type="date"
                required
                value={newTargetDate}
                onChange={(e) => setNewTargetDate(e.target.value)}
                className="w-full text-xs p-2.5 border border-slate-300 rounded-lg focus:ring-2 focus:ring-purple-700 outline-hidden"
              />
            </div>

            <div className="flex items-center justify-end gap-2 pt-2 border-t border-slate-200">
              <button
                type="button"
                onClick={() => setRescheduleModalOpen(false)}
                className="text-xs px-3 py-1.5 text-slate-600 hover:text-slate-900"
              >
                Cancel
              </button>
              <button
                type="submit"
                className="px-4 py-2 bg-purple-900 text-white rounded-lg text-xs font-bold hover:bg-purple-950 transition-colors"
              >
                Recalculate All Deadlines
              </button>
            </div>
          </form>
        </div>
      )}

      {/* Milestone Modal */}
      {milestoneModalOpen && (
        <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-slate-900/60 backdrop-blur-xs">
          <form
            onSubmit={handleSaveMilestone}
            className="bg-white rounded-2xl shadow-2xl border border-slate-200 max-w-md w-full p-6 space-y-4 animate-in fade-in zoom-in-95"
          >
            <h3 className="text-base font-bold text-slate-900 font-editorial">
              {editingMilestone ? 'Edit Milestone' : 'Add Custom Milestone'}
            </h3>

            <div>
              <label className="block text-xs font-medium text-slate-700 mb-1">Milestone Title</label>
              <input
                type="text"
                required
                value={mTitle}
                onChange={(e) => setMTitle(e.target.value)}
                placeholder="e.g. Finalize bridal makeup trial"
                className="w-full text-xs p-2.5 border border-slate-300 rounded-lg focus:ring-2 focus:ring-purple-700 outline-hidden"
              />
            </div>

            <div className="grid grid-cols-2 gap-3">
              <div>
                <label className="block text-xs font-medium text-slate-700 mb-1">Category</label>
                <input
                  type="text"
                  value={mCategory}
                  onChange={(e) => setMCategory(e.target.value)}
                  placeholder="e.g. Styling / AV / Venue"
                  className="w-full text-xs p-2.5 border border-slate-300 rounded-lg focus:ring-2 focus:ring-purple-700 outline-hidden"
                />
              </div>

              <div>
                <label className="block text-xs font-medium text-slate-700 mb-1">Priority</label>
                <select
                  value={mPriority}
                  onChange={(e) => setMPriority(e.target.value as TaskPriority)}
                  className="w-full text-xs p-2.5 border border-slate-300 rounded-lg focus:ring-2 focus:ring-purple-700 outline-hidden bg-white"
                >
                  <option value="high">High</option>
                  <option value="medium">Medium</option>
                  <option value="low">Low</option>
                </select>
              </div>
            </div>

            <div>
              <label className="block text-xs font-medium text-slate-700 mb-1">Due Date</label>
              <input
                type="date"
                required
                value={mDueDate}
                onChange={(e) => setMDueDate(e.target.value)}
                className="w-full text-xs p-2.5 border border-slate-300 rounded-lg focus:ring-2 focus:ring-purple-700 outline-hidden"
              />
            </div>

            <div>
              <label className="block text-xs font-medium text-slate-700 mb-1">Notes</label>
              <textarea
                rows={2}
                value={mNotes}
                onChange={(e) => setMNotes(e.target.value)}
                placeholder="Checklist specifications..."
                className="w-full text-xs p-2.5 border border-slate-300 rounded-lg focus:ring-2 focus:ring-purple-700 outline-hidden"
              />
            </div>

            <div className="flex items-center justify-end gap-2 pt-2 border-t border-slate-200">
              <button
                type="button"
                onClick={() => setMilestoneModalOpen(false)}
                className="text-xs px-3 py-1.5 text-slate-600 hover:text-slate-900"
              >
                Cancel
              </button>
              <button
                type="submit"
                className="px-4 py-2 bg-purple-900 text-white rounded-lg text-xs font-bold hover:bg-purple-950 transition-colors"
              >
                Save Milestone
              </button>
            </div>
          </form>
        </div>
      )}
    </div>
  );
};
